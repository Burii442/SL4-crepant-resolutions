def read(name):
    return json.loads((ROOT / name).read_text())


def digest(name):
    return hashlib.sha256((ROOT / name).read_bytes()).hexdigest()


def require(condition, message):
    if not condition:
        raise ValueError(message)


def link(path, label=None):
    return '[' + (label or path) + '](../../' + path + ')'


